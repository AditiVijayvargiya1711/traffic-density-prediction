import json
import numpy as np
import pandas as pd
from collections import defaultdict

import torch
import torch.nn as nn
from torch.utils.data import Dataset, DataLoader

from sklearn.metrics import accuracy_score, classification_report

# =====================================================
# 1. LOAD DATA
# =====================================================
with open("data/drone-mscoco.json", "r") as f:
    data = json.load(f)

annotations = data["annotations"]

vehicle_classes = {2, 3, 6, 8}
FPS = 30

# =====================================================
# 2. BUILD DENSITY PER SECOND
# =====================================================

from collections import defaultdict

frame_counts = defaultdict(int)

for ann in annotations:
    if ann["category_id"] in vehicle_classes:
        frame_counts[ann["image_id"]] += 1

sec_density = defaultdict(list)

for frame_id, count in frame_counts.items():
    sec = frame_id // FPS
    sec_density[sec].append(count)

density = []

for sec in sorted(sec_density.keys()):
    density.append(np.mean(sec_density[sec]))

density = np.array(density)
# =====================================================
# 3. SMOOTH SIGNAL
# =====================================================
density = np.convolve(density, np.ones(3)/3, mode="same")
# =====================================================
# 4. FEATURE ENGINEERING (VERY IMPORTANT)
# =====================================================
df = pd.DataFrame({"density": density})

df["mean_5"] = df["density"].rolling(5).mean().fillna(0)
df["std_5"] = df["density"].rolling(5).std().fillna(0)
df["diff1"] = df["density"].diff().fillna(0)
df["diff2"] = df["diff1"].diff().fillna(0)

features = df[["density", "mean_5", "std_5", "diff1"]].values


# =====================================================
# 5. LABEL CREATION (ROBUST THRESHOLD)
# =====================================================

# normalize each feature
features = (features - features.mean(axis=0)) / (features.std(axis=0) + 1e-8)

# =====================================================
# 6. SEQUENCE CREATION
# =====================================================
LOOKBACK = 20
HORIZON = 60

density_mean = density.mean()
density_std = density.std()

density_norm = (density - density_mean) / (density_std + 1e-8)

X, y = [], []

for i in range(len(features) - LOOKBACK - HORIZON):
    X.append(features[i:i+LOOKBACK])
    y.append(density[i + LOOKBACK + HORIZON - 1])

X = np.array(X)
y = np.array(y)

np.save("density_mean.npy", density_mean)
np.save("density_std.npy", density_std)

print("X shape:", X.shape)
print("y shape:", y.shape)

# =====================================================
# 7. TIME SERIES SPLIT (NO LEAKAGE)
# =====================================================
THRESHOLD = np.percentile(features[:, 0], 70) 
labels = (features[:, 0] > THRESHOLD).astype(int) 
print("Class distribution:", np.bincount(labels))

normal_idx = np.where(labels == 0)[0]-80
cong_idx = np.where(labels == 1)[0]-80
ni,ci=[],[]
for i in normal_idx:
    if i>=0:
        ni.append(i)
for i in cong_idx:
    if i>=0:
        ci.append(i)

np.random.seed(42)
np.random.shuffle(ni)
np.random.shuffle(ci)

split_n = int(0.8 * len(ni))
split_c = int(0.8 * len(ci))

train_idx = np.concatenate([ni[:split_n], ci[:split_c]])
test_idx  = np.concatenate([ni[split_n:], ci[split_c:]])

train_idx.sort()
test_idx.sort()
train_idx=[int(i) for i in train_idx]
test_idx=[int(i) for i in test_idx]
X_train, X_test = X[train_idx], X[test_idx]
y_train, y_test = y[train_idx], y[test_idx]
# =====================================================
# 8. DATASET
# =====================================================
class TrafficDataset(Dataset):
    def __init__(self, X, y):
        self.X = torch.tensor(X, dtype=torch.float32)
        self.y = torch.tensor(y, dtype=torch.float32)

    def __len__(self):
        return len(self.X)

    def __getitem__(self, idx):
        return self.X[idx], self.y[idx]

train_loader = DataLoader(TrafficDataset(X_train, y_train), batch_size=16, shuffle=True)
test_loader  = DataLoader(TrafficDataset(X_test, y_test), batch_size=16)
# =====================================================
# 9. CNN MODEL (STRONG FOR SMALL TIME SERIES)
# =====================================================
class CNNModel(nn.Module):
    def __init__(self, n_features=4):
        super().__init__()

        self.conv = nn.Sequential(
            nn.Conv1d(n_features, 32, kernel_size=3, padding=1),
            nn.ReLU(),
            nn.Conv1d(32, 64, kernel_size=3, padding=1),
            nn.ReLU()
        )

        self.fc = nn.Sequential(
            nn.Linear(64, 32),
            nn.ReLU(),
            nn.Linear(32, 1)
        )

    def forward(self, x):
        x = x.permute(0, 2, 1)  # (batch, features, time)
        x = self.conv(x)
        x = torch.mean(x, dim=2)
        return self.fc(x)

model = CNNModel()

# =====================================================
# 10. LOSS (WITH CLASS WEIGHTS)
# =====================================================

# Regression Loss
loss_fn = nn.HuberLoss()    

optimizer = torch.optim.Adam(
    model.parameters(),
    lr=0.001
)
print("done")
# =====================================================
# 11. TRAINING LOOP
# =====================================================
EPOCHS = 400

for epoch in range(EPOCHS):
    model.train()
    total_loss = 0

    for xb, yb in train_loader:
        optimizer.zero_grad()
        pred = model(xb).squeeze()

        loss = loss_fn(pred, yb)
        loss.backward()
        optimizer.step()
        total_loss += loss.item()

    print(f"Epoch {epoch+1} | Loss: {total_loss:.4f}")

# =====================================================
# 12. EVALUATION
# =====================================================
from sklearn.metrics import mean_absolute_error
from sklearn.metrics import mean_squared_error
from sklearn.metrics import r2_score

model.eval()

y_true = []
y_pred = []

with torch.no_grad():

    for xb, yb in test_loader:

        pred = model(xb).squeeze()

        y_true.extend(
            yb.cpu().numpy().reshape(-1).tolist()
        )

        y_pred.extend(
            pred.cpu().reshape(-1).numpy().tolist()
        )

y_true = np.array(y_true)
y_pred = np.array(y_pred)

mae = mean_absolute_error(y_true, y_pred)
rmse = np.sqrt(mean_squared_error(y_true, y_pred))
r2 = r2_score(y_true, y_pred)

print("\n===== RESULTS =====")
print("MAE :", mae)
print("RMSE:", rmse)
print("R2  :", r2)


model.eval()

with torch.no_grad():
    pred = model(
        torch.tensor(X_test, dtype=torch.float32)
    ).squeeze().numpy()
print("Predicted:", pred[:5])
print("Actual   :", y_test[:5])

torch.save(model.state_dict(), "cnn_traffic_model.pth")
feature_mean = df[["density","mean_5","std_5","diff1"]].values.mean(axis=0)
feature_std = df[["density","mean_5","std_5","diff1"]].values.std(axis=0)

np.save("feature_mean.npy", feature_mean)
np.save("feature_std.npy", feature_std)